import Player from "../models/Player.js";

async function pushPlayer(player) {
    try {
        let p = await Player.findOne({
            name: player.name,
            position: player.position,
        });
        if (p) {
            p.team = player.team;
            if (!p.stats.some((stat) => stat.season === player.stats[0].season)) {
                p.stats.push(player.stats[0]);
            } else {
                p.stats = p.stats.map((s) =>
                    s.season !== player.stats[0].season ? s : player.stats[0]
                );
            }
            if (player.yearsOfExperience) {
                p.yearsOfExperience = player.yearsOfExperience;
            }
        } else {
            p = new Player(player);
        }
        return p.save();
    } catch (e) {
        console.log(e.message);
    }
}

