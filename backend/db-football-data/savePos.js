function buildStats(mapping, numbers) {
    const stats = {};
    for (const key in mapping) {
        if (typeof mapping[key] === "number") {
            stats[key] = numbers[mapping[key]];
        } else if (typeof mapping[key] === "object") {
            stats[key] = buildStats(mapping[key], numbers);
        }
    }
    return stats;
}

function parsePlayer(row, filename, mapping) {
    const info = row.slice(0, 3);
    const numbers = row.slice(3).map(Number);
    let season = "Weighted Average";
    const year = /\d+/.exec(filename);
    if (year) season = year[0];
    const player = {
        name: info[0],
        team: info[1],
        position: info[2],
        stats: [
            {
                season,
                ...buildStats(mapping, numbers),
            },
        ],
    };
    if (filename.includes("all.csv")) {
        player.yearsOfExperience = numbers[numbers.length - 4];
        player.stats[0].half.projected = {
            mean: numbers[numbers.length - 3],
            sum: numbers[numbers.length - 2],
            rank: numbers[numbers.length - 1],
        };
    }
    return pushPlayer(player);
}

